"""Generate value-type dispatch from the reviewed wire layouts."""

import argparse
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    types = json.loads((ROOT / "tools/value_types.json").read_text())
    assert len({row["cpp"] for row in types}) == len(types)
    content = "// SPDX-License-Identifier: MIT\n// Generated by tools/generate.py; edit tools/value_types.json.\n"
    channels = {"numbers": "numbers", "signed": "signed_values", "unsigned": "unsigned_values", "texts": "texts"}
    content += "".join(
        f"USDM_VALUE_TYPE({row['cpp']}, {row['width']}, {channels[row['channel']]})\n"
        for row in types
    )
    pin = tomllib.loads((ROOT / "pixi.toml").read_text())["dependencies"][
        "openusd"
    ].removeprefix("==")
    major, minor, *_ = pin.split(".")
    version = int(major) * 100 + int(minor)
    outputs = {
        "native/value_types.inc": content,
        "native/sdk_pin.h": "// SPDX-License-Identifier: MIT\n// Generated by tools/generate.py.\n#define USDM_EXPECTED_SDK_VERSION "
        + str(version)
        + "\n",
        "src/usd_mojo/_sdk_pin.mojo": "# SPDX-License-Identifier: MIT\n# Generated by tools/generate.py.\ncomptime EXPECTED_SDK_VERSION = "
        + str(version)
        + "\n",
    }
    for name, body in outputs.items():
        target = ROOT / name
        if check:
            if not target.is_file() or target.read_text() != body:
                raise ValueError(
                    "Stale generated file " + name + "; run python tools/generate.py"
                )
        else:
            target.write_text(body)
    return len(types)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(generate(parser.parse_args().check), "wire layouts")
